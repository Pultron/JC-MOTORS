import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import test from 'node:test';

// Static guard (no app needed): the capability lists only the app's own allow-* permissions.
const capability = JSON.parse(readFileSync('src-tauri/capabilities/default.json', 'utf8'));
const buildRs = readFileSync('src-tauri/build.rs', 'utf8');
const libRs = readFileSync('src-tauri/src/lib.rs', 'utf8');
const cargo = readFileSync('src-tauri/Cargo.toml', 'utf8');
const conf = readFileSync('src-tauri/tauri.conf.json', 'utf8');

const SHARE_COMMANDS = ['save_shared_pdf', 'copy_file_to_clipboard', 'reveal_in_folder', 'open_whatsapp', 'open_mailto', 'open_gmail'];

test('capability contains only app-command allow-* permissions (no core, fs, shell, dialog, opener)', () => {
  for (const permission of capability.permissions) {
    assert.match(permission, /^allow-[a-z0-9-]+$/, `permiso inesperado: ${permission}`);
    assert.doesNotMatch(permission, /^(core|fs|shell|dialog|opener|http|process|os|clipboard-manager)/, permission);
  }
  assert.equal(new Set(capability.permissions).size, capability.permissions.length, 'permisos duplicados');
});

test('sharing commands are declared in build.rs, registered in lib.rs and allowed in the capability', () => {
  for (const command of SHARE_COMMANDS) {
    assert.ok(buildRs.includes(`"${command}"`), `${command} falta en build.rs`);
    assert.ok(libRs.includes(`async fn ${command}(`), `${command} falta en lib.rs`);
    assert.ok(libRs.slice(libRs.indexOf('generate_handler!')).includes(`${command},`) || libRs.slice(libRs.indexOf('generate_handler!')).includes(`${command}
`), `${command} falta en generate_handler!`);
    assert.ok(capability.permissions.includes(`allow-${command.replaceAll('_', '-')}`), `${command} falta en la capability`);
    assert.ok(existsSync(`src-tauri/permissions/autogenerated/${command}.toml`), `${command}.toml no generado`);
  }
});

const CLOSE_COMMANDS = ['set_close_guard', 'close_app_window'];

test('window-close guard commands are app-owned: declared, registered and allowed (no window/event permissions)', () => {
  for (const command of CLOSE_COMMANDS) {
    assert.ok(buildRs.includes(`"${command}"`), `${command} falta en build.rs`);
    assert.ok(libRs.includes(`fn ${command}(`), `${command} falta en lib.rs`);
    assert.ok(libRs.slice(libRs.indexOf('generate_handler!')).includes(command), `${command} falta en generate_handler!`);
    assert.ok(capability.permissions.includes(`allow-${command.replaceAll('_', '-')}`), `${command} falta en la capability`);
    assert.ok(existsSync(`src-tauri/permissions/autogenerated/${command}.toml`), `${command}.toml no generado`);
  }
  assert.ok(capability.permissions.every((p) => !/^(core|window|event)/.test(p)));
});

test('every capability permission maps to a command declared in build.rs', () => {
  for (const permission of capability.permissions) {
    const command = permission.slice('allow-'.length).replaceAll('-', '_');
    assert.ok(buildRs.includes(`"${command}"`), `${permission} no corresponde a un comando de build.rs`);
  }
});

test('no opener/shell/fs plugin and no wildcard URL scopes', () => {
  assert.doesNotMatch(cargo, /tauri-plugin-(opener|shell|fs|http|clipboard-manager)/);
  assert.doesNotMatch(libRs, /tauri_plugin_(opener|shell|fs|http|clipboard_manager)/);
  assert.doesNotMatch(JSON.stringify(capability), /"(url|path|scope)"|\*/);
});

test('CSP does not allow any network access', () => {
  const csp = JSON.parse(conf).app.security.csp;
  const connect = csp.match(/connect-src ([^;]*)/)[1];
  assert.equal(connect.trim(), "'self' ipc: http://ipc.localhost");
  assert.doesNotMatch(csp, /https?:\/\/(?!ipc\.localhost)|\*/);
});
